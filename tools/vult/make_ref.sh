# Phantom Tracker 0.9.10: VULT's references. Compiles Vult's own ladder and comb (github.com/vult-dsp/vult examples, MIT)
# with the Vult compiler (npm: vult 0.4.15) to float C++, renders the five cases of tests/vult_test.c and writes their
# harmonic levels (dB, harmonics 1..39 of 110 Hz, over the second half of 0.2 s) to tests/vult_ref.h.
#   sh tools/vult/make_ref.sh VULT_EXAMPLES_DIR      (a checkout of github.com/vult-dsp/vult: its examples/)
set -e
EX=$1; T=$(mktemp -d); HERE=$(cd "$(dirname "$0")" && pwd)
for m in effects/rescomb filters/ladder effects/saturate_soft util/util util/tables; do
    b=$(basename $m); cp "$EX/$m.vult" "$T/$(echo $b | cut -c1 | tr a-z A-Z)$(echo $b | cut -c2-).vult"; done
cp "$HERE/ref.vult" "$HERE/ref_main.cpp" "$T/"
(cd "$T" && npx -y vult@0.4.15 ref.vult -ccode -real float -o ref_gen -i . && curl -s -o vultin.h https://raw.githubusercontent.com/modlfo/vult-examples/master/src/vultin.h \
   && curl -s -o vultin.c https://raw.githubusercontent.com/modlfo/vult-examples/master/src/vultin.c && g++ -O1 -o ref ref_main.cpp ref_gen.cpp vultin.c)
python3 - "$T/ref" "$HERE/../../tests/vult_ref.h" <<'PY'
import sys, subprocess, numpy as np
ref, out = sys.argv[1], sys.argv[2]
CASES = [(0, 0.5, 0.8), (0, 0.3, 0.2), (0, 0.4, 1.0), (1, 0.3, 0.8), (1, 0.45, 0.5)]
rows = []
for c in CASES:
    y = np.array([float(v) for v in subprocess.check_output([ref] + [str(a) for a in c]).split()])[4410:]
    n = len(y); w = np.hanning(n)
    lv = [20 * np.log10(abs(np.sum(w * y * np.exp(-2j * np.pi * k * 110 * np.arange(n) / 44100))) + 1e-9) for k in range(1, 40)]
    rows.append("    {%d, %.2f, %.2f, {%s}}," % (c[0], c[1], c[2], ", ".join("%.2f" % v for v in lv)))
open(out, "w").write("/* generated by tools/vult/make_ref.sh from Vult's own ladder and comb (MIT): do not edit */\n"
    "static const struct { int mode; double cv, res; double db[39]; } VULT_REF[] = {\n" + "\n".join(rows) + "\n};\n")
PY
rm -rf "$T"
